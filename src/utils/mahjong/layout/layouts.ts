export const LAYOUTS: Record<LayoutId, LayoutDefinition> = {
	turtle: { id: "turtle", name: "Turtle", layers: TURTLE_LAYERS },
	pyramid: { id: "pyramid", name: "Pyramid", layers: PYRAMID_LAYERS },
	fortress: { id: "fortress", name: "Fortress", layers: FORTRESS_LAYERS },
};

export const LAYOUT_LIST: readonly LayoutDefinition[] = [
	LAYOUTS.turtle,
	LAYOUTS.pyramid,
	LAYOUTS.fortress,
];

export const LAYER_LAYOUTS = TURTLE_LAYERS;

export function getDailyLayout(puzzleNumber: number): LayoutDefinition {
	const index =
		(((puzzleNumber - 1) % LAYOUT_LIST.length) + LAYOUT_LIST.length) %
		LAYOUT_LIST.length;
	return LAYOUT_LIST[index];
}

export function countTotalTiles(
	layerLayouts: number[][][] = TURTLE_LAYERS,
): number {
	return layerLayouts.reduce(
		(total, layer) =>
			total + layer.flat().filter((val) => val >= 1 && val <= 3).length,
		0,
	);
}
